            <h3>How to Lead God Compliant family Life? </h3> 
        <p style="text-align: left;">&nbsp&nbsp&nbsp&nbsp <b>'mama vartmānuvartante manuṣhyāḥ pārtha sarvaśhaḥ'</b>- Whatsoever, a great man does, the same is done by others, as well (Gita 3/21). God is the supreme Being. He [God/ She/ They] is superior to the all the great men. So all people follow Him [Her/ Them]. The same fact, has been pointed out, in the second half of the twenty-third verse of the third chapter. </p>
    <h4 id="41parent">4.1 Feeling towards parent</h4>
	<p style="text-align: left;">&nbsp&nbsp&nbsp&nbsp The Lord, ever remains prepared to reciprocate the sentiment of His [Her/ Their] devotee. [Let's take the example of Lord Sita Rāma (Das, 2006, Pg. 483)] King Daśratha treats Him [Her/ Them], as his [her / their] son [daughter / LGBTQI+ child]. So He [She/ They] becomes/become an obedient son [daughter / LGBTQI+ child] and cannot disobey His [ Her / Their] father.* The Lord, wants to reveal the secret that a devotee should accept the same relationship with Him [Her/Them], which he [she/ they] has/have with a person who is most loving to him [her/ them], whether he [she/ they] is his [her/ their] son [daughter / LGBTQI+ child], father or whether she [ he/ they] is/are his [her/ their] mother. By doing so, the Lord will become most loving to him [her/ them] and thus the person will be able to attain Him [ Her/ Them] easily.</p>
    <h4 id="42family">4.2 Feeling towards spouse, sibling and relatives</h4>
	<p style="text-align: left;">&nbsp&nbsp&nbsp&nbsp Secondly, the Lord wants to urge the people, that by following His [Her/ Them] footsteps they should also become worthy sons or parents or brothers, husbands, wifes or sisters etc. Moreover, they should render service to other members of a family, without expecting any reward from them and without being proud of their actions. Those who have affinity with parents and other relatives, only for rendering selfless service to them, follow the Lord's path in the real sense. By doing so, for the good of others they will be free from the feeling of 'mine', and they will develop devotion for God and attain Him [Her/ Them]. </p>
	    <h4 id="43everyone">4.3 Feeling Towards All</h4>
	<p style="text-align: left;">&nbsp&nbsp&nbsp&nbsp Thirdly, towards society in general following must be followed (rgmedia108, 2018, Jan, 19):</p>
    <h4 id="431superior">4.3.1 Feeling Towards Superior</h4>
    <p style="text-align: left;">Be pleased and happy for them. Serve them nicely. Do not envy or get depressed.</p>
    <h4 id="431novice">4.3.2 Feeling Towards Learner</h4>
    <p style="text-align: left;"> Feel deep compassion for them. Genuinely try to uplift them. Do not misuse your superiority in the situation.</p>
    <h4 id="433novice">4.3.3 Feeling Towards an Equal</h4> 
    <p style="text-align: left;">Become friends. Be genuine well wisher and try to uplift each other. Do not boast or show off.</p>

<p style="text-align: left;">* Lord Rāma declares, "I can enter fire, can eat deadly poison and can jump into the sea in order to carry out the order of My father (Vālmīki Rāmāyaņa, Ayodhyā. 18/28-29)".</p>
<p style="text-align: left;">Source: Section 4.1 and 4.2 are sourced from Chapter 4 Verse 11 (Das, 2006, Pg. 490)</p>
