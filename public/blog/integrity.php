        <h2 id="4context">4.0 CONTEXT </h2>

        
    <p style="text-align: left;"> New Zealand is blessed that despite when it was colonised in 1840 by the British Crown, good people on both sides of the table had the foresight to setup an agreement between the Crown and the Indigenous people in order to minimise the harm. The agreement is called the "The Treaty of Waitangi".</p>
    <p style="text-align: left;">
        While history of colonisation across the world speaks for itself, due to the treaty a lot of genuine and systematic redress occured in New Zealand starting from the latter half of the 20st Century, like no where else in the Western world. It was around this time that the 
        'Resource Management Act' (RMA) was conjured up by the leaders of the country and enacted in Parliament. From what I understand, it provided much of the legal frameworks to enable the consultations that occured and continues to facilitate them. The buy product is that New Zealand was left with a world class tool for managing difficult conversations and complex problems. </p>
        
                
        <h2 id="5short-view-of-world">5.0 SHORT SIGHTED VIEW OF THE WORLD ATTACKS RMA</h2>
        <p>------------------------------------------------</p>
        <p style="text-align: left;"> I am not a NZ Government employee, nor am I officially affiliated to any political movement. My vote goes to the ones who talk sanity. I am an IEEE Engineer from the university of Auckland. My education in the Engineering profession in early 2000's was forged on the basis of the 'Resource Management Act' (RMA). The current administration of New Zealand is raising questions about RMA. I agree that RMA does involve processes perceived as conscientious, as it is incumbent on the leaders of the day to involve consultations with all stakeholders (including local tribes) with the aim of getting a 'win-win' prior to commencing  engineering activities that impact them, in order to proceed with good faith (IEEE, 2026). This must be attempted at all costs (Firsts and Lasts, 2026, Jan, 13). </p>
        <p style="text-align: left;">The 'government of the day' has tried to find its feet courageously in a changing environment marred by wars, distrust, technology challenges, cyber and physical threats neven seen before (Infogain Hub Channel, 2025, March, 19).</p>
         <p style="text-align: left;">Still in this period of massive change, some forces that take unfair advantage of the situation of suffering of many, created an atmosphere where dissension and hate were built up in order to polarise votes. In order to balance the public good and public opinion, the current coalition goverenment in 2024, brought a peice of legislation to parliament called the Treaty Principles Bill. It made New Zealanders question who they were as rallies and prominent personalities cautioned us about the risks of going backwards on years of evolution, and to speak out against it, such as New Zealand's first female and now ex prime minister Dame Jenny Shipley(McCulloch, 2024, November 16):</p><br><br>
         
